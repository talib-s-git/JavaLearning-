package day1;

public class VariablesDataTypes {

	public static void main(String[] args) {
		byte by=50;        // (small whole numbers)
		short sh=3200;     // (Medium whole numbers)
		int in=26;      // (Whole numbers NO DECIMAL)
		long lo=471384141837L;   //(Large whole numbers)
		double du=3333.3;      //(Large Decimal numbers) 
		float fl=55.5F;       // (Small Decimal numbers)
		char ch='T';         // (Single character)
		boolean bool=true;   //(True or False values)
		String name="Talib";  //(Text)
		
		System.out.println(by);
		System.out.println(sh);
		System.out.println(in);
		System.out.println(lo);
		System.out.println(du);
		System.out.println(fl);
		System.out.println(ch);
		System.out.println(bool);
		System.out.println(name);
		

	}

}
